package com.itheima.literl.looploop;

public class Test7 {
    /*
    制表符：
    \t:是一个长度可变的空格，用于对齐，可以上下对齐，例如九九乘法表

    制表符真正的含义：
    在前面的字符后面补1-4个空格，让整体凑成4的整数倍'不能补0个空格
    有的idea会补成8的整数倍
     */
    public static void main(String[] args){
        System.out.println("name \t age \t gender");
        System.out.println("张三 \t 18 \t 男");
        System.out.println("李四 \t 19 \t 女");

        System.out.println("--------");
        System.out.println("--\t--");
    }
}
