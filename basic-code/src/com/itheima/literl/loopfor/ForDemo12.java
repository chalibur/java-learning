package com.itheima.literl.loopfor;

public class ForDemo12 {
    /*
    无限循环：
    1.for格式：
    for(;;){
        System.out.println("hello world");
    }
    2.while格式：
    while(true){
        System.out.println("hello world");
    }
    3.do while格式：
    do{
        System.out.println("hello world");
    }while(true);
     */
    public static void main(String[] args){
        for(;;){
            System.out.println("hello world");
        }
    }

}
